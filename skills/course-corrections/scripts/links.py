#!/usr/bin/env python3
"""Repair a broken heading anchor by looking the right one up, never by guessing.

Obsidian warns about a missing file and says nothing about a missing heading, so
a section renamed in lesson 3 quietly invalidates lesson 9's link to it. Over a
semester the vault rots that way and **no other skill repairs it**: A rewrites
link targets only during a code rename or a renumber, B reports without fixing,
and C never writes into the notes at all. Without this module the rot is
permanent (D-30).

The repair is narrow, and each narrowing is load-bearing:

  * **The right anchor is looked up, not guessed.** The old anchor text finds
    the concept in `concepts.json`; the concept finds its current heading in the
    target file. A fuzzy match to the most similar heading in the file is how a
    link ends up pointing confidently at the wrong section.
  * **A retired concept is proposed by its successor and asked about**, the same
    rule replay uses.
  * **Each one appears in the plan with the old and the new anchor. None is
    bulk-applied.**
  * **A broken *file* link is reported only.** It means a missing lesson or a
    filing problem, which belongs to A or B.
  * **Nothing under `Explanations/` is touched** (G20). A broken link in a saved
    explanation is course-explain's to repair, and D never writes there.

CLI:
    links.py check  --vault <path> --course <path>
    links.py repair --vault <path> --course <path>   -> proposed edits for apply.py
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[2] / 'shared' / 'scripts'))
sys.path.insert(0, str(HERE))
import anchor                                                     # noqa: E402
import check_links                                                # noqa: E402
import naming                                                     # noqa: E402

LESSON_TOKEN_RE = re.compile(r'(?<![A-Za-z0-9])([LT]\d{2})(?![A-Za-z0-9])')


def _lesson_of(name: str) -> str | None:
    m = LESSON_TOKEN_RE.search(naming.strip_code_token(name))
    return m.group(1) if m else None


def check(vault: Path | str, course: Path | str) -> dict:
    """Broken links inside this course, split into D's half and the report-only half."""
    vault, course = Path(vault), Path(course)
    raw = check_links.check(vault, scope=course)

    def owner(row):
        # A link that lives inside Explanations/ is course-explain's to repair.
        # A link inside .work/ or .data/ is a machine file D reads and never
        # writes — repairing it there would be an edit to another skill's output
        # for no reader's benefit.
        parts = Path(row['in']).parts
        if 'Explanations' in parts:
            return 'explain'
        if '.work' in parts or '.data' in parts:
            return 'machine'
        return 'mine'

    grouped = {'mine': [], 'explain': [], 'machine': []}
    for row in raw['broken_heading_anchors']:
        grouped[owner(row)].append(row)
    return {'checked': raw['checked'],
            'broken_heading_anchors': grouped['mine'],
            'in_explanations': grouped['explain'],
            'in_machine_files': grouped['machine'],
            'broken_file_links': raw['broken_file_links'],
            'ambiguous_targets': raw['ambiguous_targets'],
            'note': {
                'anchors': 'D repairs these, as a logged replace on the link target',
                'in_explanations': 'course-explain repairs its own links; D never '
                                   'writes into Explanations/',
                'in_machine_files': 'a stale anchor inside .work/ or .data/ is '
                                    'regenerated by its owner; D never edits those',
                'files': 'reported only: a missing file belongs to course-setup or '
                         'course-notes',
                'ambiguous': 'two files share this name; course-setup resolves that'}}


def _concept_for_heading(registry: dict, heading: str, lesson: str | None) -> list[dict]:
    """Which concept used to be called this, preferring the target lesson's own."""
    out = []
    for cid, data in (registry.get('concepts') or {}).items():
        for s in data.get('sections') or []:
            if (s.get('heading') or '').strip() != heading.strip():
                continue
            out.append({'concept': cid, 'lesson': s.get('lesson'),
                        'retired': bool(data.get('retired')),
                        'title': data.get('title')})
    if lesson:
        preferred = [r for r in out if r['lesson'] == lesson]
        if preferred:
            return preferred
    return out


def _current_heading(notes: str, concept: str) -> str | None:
    section = anchor.section_for(notes, concept)
    return section['heading'] if section else None


def repair(vault: Path | str, course: Path | str) -> dict:
    """One proposed edit per broken anchor, each with its old and new value."""
    vault, course = Path(vault), Path(course)
    found = check(vault, course)
    registry = anchor.load_concepts(course / '.data' / 'concepts.json')

    edits, ask, stuck = [], [], []
    for row in found['broken_heading_anchors']:
        target = vault / row['target']
        lesson = _lesson_of(Path(row['target']).name)
        notes = target.read_text(encoding='utf-8') if target.is_file() else ''
        candidates = _concept_for_heading(registry, row['anchor'], lesson)

        if not candidates:
            stuck.append({**row, 'reason':
                          'no concept in the registry ever carried this heading, so '
                          'there is nothing to look the new one up by'})
            continue
        if len(candidates) > 1:
            ask.append({**row, 'candidates': candidates,
                        'question': 'more than one concept once carried this heading; '
                                    'which did this link mean?'})
            continue

        found_concept = candidates[0]
        new_heading = _current_heading(notes, found_concept['concept'])
        if new_heading is None or found_concept['retired']:
            succ = anchor.successor(registry, found_concept['concept'],
                                    lesson or found_concept['lesson'] or '')
            ask.append({**row, 'concept': found_concept['concept'],
                        'retired': found_concept['retired'], 'successor': succ,
                        'question': 'that concept is no longer in the target file. '
                                    'Point the link at the successor below, or leave '
                                    'the link broken and say so in the report.'})
            continue
        if new_heading == row['anchor']:
            stuck.append({**row, 'reason':
                          'the registry and the file agree on this heading, so the '
                          'link is broken for another reason'})
            continue

        before = row['link']
        after = before.replace('#' + row['anchor'], '#' + new_heading, 1)
        edits.append({'file': row['in'], 'operation': 'replace',
                      'before': before, 'after': after,
                      'concept': found_concept['concept'],
                      'target': row['target'],
                      'old_anchor': row['anchor'], 'new_anchor': new_heading,
                      'verify': 'text',
                      'evidence_text': f'concepts.json: {found_concept["concept"]} is '
                                       f'now "{new_heading}" in {row["target"]}'})

    return {'edits': edits, 'ask': ask, 'not_repairable': stuck,
            'reported_only': {'broken_file_links': found['broken_file_links'],
                              'ambiguous_targets': found['ambiguous_targets'],
                              'in_explanations': found['in_explanations'],
                              'in_machine_files': found['in_machine_files']},
            'note': 'every row goes in the plan with its old and new anchor; none is '
                    'bulk-applied'}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    sub = ap.add_subparsers(dest='cmd', required=True)
    for name in ('check', 'repair'):
        p = sub.add_parser(name)
        p.add_argument('--vault', required=True); p.add_argument('--course', required=True)
    args = ap.parse_args(argv)
    out = check(args.vault, args.course) if args.cmd == 'check' \
        else repair(args.vault, args.course)
    json.dump(out, sys.stdout, ensure_ascii=False, indent=2, default=str)
    sys.stdout.write('\n')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
