#!/usr/bin/env python3
"""Workbooks to Pass A items: one ID per sheet, per row block, per formula map.

**A workbook read for its values alone loses the tutorial.** In a finance or
engineering workshop the lecturer's answer is `=B12/B30`, not the `0.42` it
evaluates to; a student who has the number and not the division has nothing to
revise from. So every block of cells is emitted twice, once as the grid the
student sees and once as the formulas behind it, and the formula item carries
its own ID so Pass D can tell whether the notes ever used the method.

That requires **two loads of the same file**, because openpyxl gives formulas
and cached values through mutually exclusive modes. The trap underneath is that
the cached values exist only if Excel itself last saved the file: a workbook
generated by a script, or never opened, returns `None` for every formula cell
under `data_only=True`. Read naively that is a grid of blanks, and it extracts,
chunks and covers exactly like a legitimately empty sheet. It is reported as a
warning on the sheet and on the run, never swallowed.

Charts and embedded images get IDs for the same reason slides do: a sheet whose
content is a plotted yield curve extracts to almost no text, and without an
explicit item Pass D reports full coverage of the one sheet that carried the
point. A cell comment is the author's own annotation and gets an ID too, on the
same footing as a margin note in a PDF.

Granularity is the *row block*, a run of non-empty rows bounded by blank ones.
Per-cell IDs would put thousands of atoms in the coverage set and make the
arithmetic meaningless; per-sheet IDs would hide the formulas inside one atom
nobody can cite precisely.

IDs (note-invariants §2):
    H04      sheet 4 of a handout workbook, its name and shape
    H04.3    third row block on that sheet
    H04.3f   -- not used; formula maps are plain sub-items, see below
    H2.1.3   third block, first sheet, of the *second* handout workbook

CLI:
    extract_xlsx.py extract --path <wb.xlsx> --entry Content/handout_x.xlsx \\
        --prefix H --work <lesson/.work> --run <ts> --hash <h> [--apply]
    extract_xlsx.py extract --path <wb.xlsx> --entry Content/notes_y.xlsx \\
        --prefix N --kind notes ...
"""
from __future__ import annotations

import argparse
import datetime as _dt
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[2] / 'shared' / 'scripts'))
sys.path.insert(0, str(HERE))
import extraction                                                  # noqa: E402

CHUNK_WORDS = 8000
MAX_ROWS = 400          # per sheet; truncation is always reported, never silent
MAX_COLS = 40
BLANK_RUN = 1           # blank rows needed to close a block


def _sheet_id(prefix: str, n: int) -> str:
    """`H` + 4 -> `H04`; `H2` + 1 -> `H2.1`.

    A prefix ending in a digit already names one workbook among several, so its
    sheets are subdivisions of it. Same rule as extract_docx._item_id.
    """
    return f'{prefix}.{n}' if prefix[-1].isdigit() else f'{prefix}{n:02d}'


def _fmt(value, number_format: str = '') -> str:
    """The cell as the student sees it on screen, not as it sits on disk.

    Percent formatting is applied because it changes the number. A ratio stored
    as 0.35 and displayed as 35% is said aloud as "thirty-five percent" in the
    recording, and leaving it as 0.35 manufactures a disagreement between the
    workbook and the transcript that no source actually contains.
    """
    if value is None:
        return ''
    if isinstance(value, bool):
        return 'TRUE' if value else 'FALSE'
    if isinstance(value, (_dt.datetime, _dt.date)):
        return value.date().isoformat() if isinstance(value, _dt.datetime) \
            else value.isoformat()
    if isinstance(value, float):
        if '%' in (number_format or ''):
            pct = value * 100
            return f'{pct:.1f}%'.replace('.0%', '%')
        if value == int(value) and abs(value) < 1e15:
            return str(int(value))
        return f'{value:,.4f}'.rstrip('0').rstrip('.')
    if isinstance(value, int) and '%' in (number_format or ''):
        return f'{value * 100}%'
    return str(value).replace('\n', ' ').strip()


def _col_letter(i: int) -> str:
    out = ''
    while i > 0:
        i, r = divmod(i - 1, 26)
        out = chr(65 + r) + out
    return out


def _blocks(rows: list[list], first_row: int) -> list[tuple]:
    """Contiguous runs of non-empty rows, as (start_row, [rows])."""
    out, cur, start = [], [], None
    blanks = 0
    for offset, row in enumerate(rows):
        if any(c != '' for c in row):
            if start is None:
                start = first_row + offset
            cur.append(row)
            blanks = 0
        elif cur:
            blanks += 1
            if blanks >= BLANK_RUN:
                out.append((start, cur))
                cur, start, blanks = [], None, 0
    if cur:
        out.append((start, cur))
    return out


def _table(rows: list[list], start_row: int, cols: list[str]) -> str:
    width = max(len(r) for r in rows)
    head = ['row'] + cols[:width]
    lines = ['| ' + ' | '.join(head) + ' |', '|' + '---|' * len(head)]
    for i, row in enumerate(rows):
        cells = [str(start_row + i)] + [row[j] if j < len(row) else ''
                                        for j in range(width)]
        lines.append('| ' + ' | '.join(cells) + ' |')
    return '\n'.join(lines)


def _sheet_items(ws_f, ws_v, sid: str, warnings: list) -> list[dict]:
    """One sheet to its items. ws_f carries formulas, ws_v cached values."""
    items = []
    hidden = getattr(ws_f, 'sheet_state', 'visible') != 'visible'
    max_row = min(ws_f.max_row or 0, MAX_ROWS)
    max_col = min(ws_f.max_column or 0, MAX_COLS)
    truncated = ((ws_f.max_row or 0) > MAX_ROWS or (ws_f.max_column or 0) > MAX_COLS)

    head = [f'Sheet "{ws_f.title}"'
            + (' (hidden in the workbook)' if hidden else '')
            + f', {ws_f.max_row or 0} rows x {ws_f.max_column or 0} columns']
    if truncated:
        note = (f'TRUNCATED: only rows 1-{max_row} and columns '
                f'A-{_col_letter(max_col)} were extracted.')
        head.append(note)
        warnings.append({'sheet': ws_f.title, 'why': note})
    items.append({'id': sid, 'tags': [], 'text': '\n'.join(head)})

    if not max_row or not max_col:
        items[-1]['text'] += '\n(the sheet is empty)'
        return items

    grid, formulas, comments = [], [], []
    stale = 0
    for r in range(1, max_row + 1):
        line = []
        for c in range(1, max_col + 1):
            cf = ws_f.cell(row=r, column=c)
            cv = ws_v.cell(row=r, column=c)
            raw = cf.value
            is_formula = isinstance(raw, str) and raw.startswith('=')
            if is_formula:
                formulas.append(f'{_col_letter(c)}{r}: {raw}')
                shown = _fmt(cv.value, cf.number_format)
                if cv.value is None:
                    stale += 1
            else:
                shown = _fmt(raw, cf.number_format)
            line.append(shown)
            cm = getattr(cf, 'comment', None)
            if cm is not None and (cm.text or '').strip():
                comments.append(f'{_col_letter(c)}{r}: '
                                + ' '.join(cm.text.split()))
        grid.append(line)

    if stale:
        note = (f'{stale} formula cell{"s" if stale > 1 else ""} ha'
                f'{"ve" if stale > 1 else "s"} no cached value: this workbook was '
                'last written by something other than Excel, so those cells are '
                'blank in the grid below. The formulas themselves are intact. '
                'Do not read the blanks as empty cells.')
        items[0]['text'] += '\n' + note
        warnings.append({'sheet': ws_f.title, 'why': note})

    cols = [_col_letter(i) for i in range(1, max_col + 1)]
    blocks = _blocks(grid, 1)
    if not blocks and not formulas:
        items[0]['text'] += '\n(the sheet has no filled cells)'
    sub = 0
    for start, rows in blocks:
        sub += 1
        items.append({'id': f'{sid}.{sub}', 'tags': [],
                      'text': f'Rows {start}-{start + len(rows) - 1}:\n'
                              + _table(rows, start, cols)})

    if formulas:
        sub += 1
        items.append({'id': f'{sid}.{sub}', 'tags': [],
                      'text': f'Formulas on sheet "{ws_f.title}" '
                              f'({len(formulas)}), cell by cell. These are the '
                              'method, not a restatement of the numbers above:\n'
                              + '\n'.join(formulas)})
    if comments:
        sub += 1
        items.append({'id': f'{sid}.{sub}', 'tags': [],
                      'text': f'Cell comments on sheet "{ws_f.title}" '
                              f'({len(comments)}):\n' + '\n'.join(comments)})

    for chart in list(getattr(ws_f, '_charts', []) or []):
        sub += 1
        title = ''
        try:
            t = chart.title
            title = ''.join(r.t or '' for p in t.tx.rich.p for r in (p.r or []))
        except Exception:
            pass
        items.append({'id': f'{sid}.{sub}', 'tags': [],
                      'text': f'[chart on sheet "{ws_f.title}"'
                              + (f': {title}' if title else '')
                              + f', type {type(chart).__name__}. Open the '
                              'workbook and read it; its content is not text.]'})
    for img in list(getattr(ws_f, '_images', []) or []):
        sub += 1
        anchor = getattr(getattr(img, 'anchor', None), '_from', None)
        where = (f' anchored at {_col_letter((anchor.col or 0) + 1)}'
                 f'{(anchor.row or 0) + 1}') if anchor is not None else ''
        items.append({'id': f'{sid}.{sub}', 'tags': [],
                      'text': f'[embedded image on sheet "{ws_f.title}"{where}. '
                              'Open the workbook and read it.]'})
    return items


def extract(path: Path | str, entry: str, prefix: str) -> dict:
    import openpyxl                                                # noqa: E402

    path = Path(path)
    try:
        wb_f = openpyxl.load_workbook(path, data_only=False)
        wb_v = openpyxl.load_workbook(path, data_only=True)
    except Exception as exc:
        raise extraction.ExtractionError(
            f'{path.name} did not open as a workbook: {exc}. If it is an .xls '
            'or a CSV renamed, convert it and re-file it; do not read it by '
            'hand.') from exc

    items, warnings = [], []
    for n, name in enumerate(wb_f.sheetnames, 1):
        sid = _sheet_id(prefix, n)
        items.extend(_sheet_items(wb_f[name], wb_v[name], sid, warnings))

    if not items:
        items.append({'id': _sheet_id(prefix, 1), 'tags': [],
                      'text': '(the workbook has no sheets)'})
    return {'path': str(path), 'entry': entry, 'sheets': len(wb_f.sheetnames),
            'items': items, 'chunks': _chunk_boundaries(items),
            'warnings': warnings}


def _chunk_boundaries(items: list[dict], limit: int = CHUNK_WORDS) -> list[str]:
    out, words = [], 0
    for item in items:
        n = len(item['text'].split())
        if words and words + n > limit:
            out.append(item['id'])
            words = 0
        words += n
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    sub = ap.add_subparsers(dest='cmd', required=True)
    p = sub.add_parser('extract')
    p.add_argument('--path', required=True)
    p.add_argument('--entry', required=True)
    p.add_argument('--prefix', required=True, help='ID stem: H, H2, N ...')
    p.add_argument('--kind', default='handout')
    p.add_argument('--work'); p.add_argument('--run', default='')
    p.add_argument('--hash', default='')
    p.add_argument('--apply', action='store_true')
    args = ap.parse_args(argv)

    out = extract(args.path, args.entry, args.prefix)
    bad = [extraction.validate_id(i['id']) for i in out['items']]
    bad = [b for b in bad if not b['ok']]
    if bad:
        raise extraction.ExtractionError(f'emitted invalid ids: {bad[:5]}')
    if args.work:
        out['written'] = extraction.write(
            args.work, args.entry, args.run, args.hash, args.kind,
            out['items'], out['chunks'], apply_it=args.apply)
    out['item_count'] = len(out['items'])
    out['ids'] = [i['id'] for i in out['items']][:20]
    del out['items']
    json.dump(out, sys.stdout, ensure_ascii=False, indent=2, default=str)
    sys.stdout.write('\n')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
